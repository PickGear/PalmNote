package com.palmnote.data.export

/**
 * CSV-ZIP 导出的范围。
 *
 * 为什么导出可以拆、备份不能拆——这是两条通道的性质决定的：
 * CSV-ZIP 是**数据交换**产物（可读的明文，给人看、给别的软件读），
 * 取出一部分是完全正当的用法；而 `.palmnote` 备份的语义是「完整可复原」，
 * 一旦允许选范围，用户就会做出「只备了一半」的备份，在换机那天才发现缺东西。
 *
 * 分组的依据是**依赖闭包**，不是「数据库里有几张表」：
 * 账单离开钱包和分类就无法解释，所以 [BILL] 必须连带钱包、周期模板、预算、
 * 分类配置与分类映射一起走。勾了账单却拿不到钱包的导出物是残缺的。
 */
enum class ExportScope {
    /** 全部模块。 */
    ALL,

    /** 记账：账单 + 钱包 + 周期模板 + 预算 + 分类配置 + 分类映射。 */
    BILL,

    /** 物品：物品 + 使用记录 + 图片。 */
    ASSET,

    /** 生活：目标 + 打卡记录 + 纪念日 + 瞬间 + 标签。 */
    LIFE;

    /**
     * 是否为完整导出。
     *
     * `preferences.json` 属于「本机设置」而非「用户内容」：部分导出（给别人读的
     * 那份清单）没有理由把本机主题、默认账单类型一并带走，导入方会被莫名改设置。
     * 所以只在完整导出时才写入该条目。
     */
    val isComplete: Boolean get() = this == ALL
}
