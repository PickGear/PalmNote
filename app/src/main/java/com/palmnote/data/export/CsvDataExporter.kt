    private fun resolveIncomingRefs(clazz: Class<*>, entity: Any, idMaps: Map<Class<*>, Map<Long, Long>>): Any {
        if (clazz != GoalCheckIn::class.java) return entity
        val checkIn = entity as? GoalCheckIn ?: return entity
