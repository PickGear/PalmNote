    private val HEADER_LABEL_TO_FIELD: Map<String, String> by lazy {
        FIELD_LABEL_CN.entries.associate { (field, label) -> label to field }
    }

    private fun csvToRows(csv: String): List<Map<String, String>> {
        val clean = csv.removePrefix("\uFEFF")
        val lines = clean.lines().filter { it.isNotBlank() }
        if (lines.size < 2) return emptyList()
        val rawHeaders = parseCsvLine(lines[0])
        val headers = rawHeaders.map { HEADER_LABEL_TO_FIELD[it] ?: it }
        return lines.drop(1).map { line ->
            val values = parseCsvLine(line)
            headers.mapIndexed { i, h -> h to (values.getOrElse(i) { "" }) }.toMap()
        }
    }

    private fun parseCsvLine(line: String): List<String> {
        val result = mutableListOf<String>()
        val current = StringBuilder()
        var inQuotes = false
        var i = 0
        while (i < line.length) {
            val ch = line[i]
            when {
                ch == '"' && !inQuotes -> inQuotes = true
                ch == '"' && inQuotes -> {
                    if (i + 1 < line.length && line[i + 1] == '"') {
                        current.append('"')
                        i++
                    } else {
                        inQuotes = false
                    }
                }
                ch == ',' && !inQuotes -> {
                    result.add(current.toString())
                    current.clear()
                }
                else -> current.append(ch)
            }
            i++
        }
        result.add(current.toString())
        return result
    }

