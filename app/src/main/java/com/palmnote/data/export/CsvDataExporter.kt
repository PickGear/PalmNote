    private fun reorderFields(fields: Iterable<String>, clazz: Class<*>): List<String> {
        val prefix = COMMON_PREFIX[clazz].orEmpty()
        val set = fields.toSet()
        return prefix.filter { it in set } + (set - prefix.toSet()).toList()
    }

    private fun buildGroupCsv(
        groupEntries: List<Pair<String, List<*>>>,
        extraColumns: Map<Class<*>, List<Pair<String, (Any?) -> Any>>> = emptyMap()
    ): String {
        val allFields = linkedSetOf<String>()
        val classExtraCols = mutableMapOf<Class<*>, List<Pair<String, (Any?) -> Any>>>()
        for ((_, entities) in groupEntries) {
            if (entities.isEmpty()) continue
            val clazz = (entities.first() ?: continue)::class.java
            entityFieldMaps[clazz]?.keys
                ?.filter { it !in (EXCLUDED_FIELDS[clazz].orEmpty()) }
                ?.let { reorderFields(it, clazz) }
                ?.let { allFields.addAll(it) }
            extraColumns[clazz]?.let { cols ->
                classExtraCols[clazz] = cols
                allFields.addAll(cols.map { it.first })
            }
        }
        val fieldNames = allFields.toList()
        val headers = listOf("实体类型") + fieldNames.map { FIELD_LABEL_CN[it] ?: it }
        val fieldLookup = headers.map { HEADER_LABEL_TO_FIELD[it] ?: it }

        val sb = StringBuilder("\uFEFF")
        sb.appendLine(headers.joinToString(",") { escapeCsv(it) })
        for ((typeName, entities) in groupEntries) {
            if (entities.isEmpty()) continue
            val clazz = (entities.first() ?: continue)::class.java
            val fieldMap = entityFieldMaps[clazz] ?: continue
            val extraForClass = classExtraCols[clazz].orEmpty()
            val typeNameEsc = escapeCsv(typeName)
            for (entity in entities) {
                val values = fieldLookup.mapIndexed { i, fieldName ->
                    if (i == 0) typeNameEsc
                    else {
                        val extraValDef = extraForClass.firstOrNull { it.first == fieldName }
                        if (extraValDef != null) {
                            valueToCsv(fieldName, extraValDef.second(entity), clazz)
                        } else {
                            val field = fieldMap[fieldName]
                            if (field != null) valueToCsv(fieldName, field.get(entity), clazz) else ""
                        }
                    }
                }
                sb.appendLine(values.joinToString(","))
            }
        }
        return sb.toString()
    }

    private fun valueToCsv(fieldName: String, value: Any?, entityClass: Class<*>): String {
        return when {
            value == null -> ""
            value is Boolean -> if (value) "是" else "否"
            value is Long && fieldName in DATE_FIELDS -> dateFormatter.format(Instant.ofEpochMilli(value).atZone(ZoneId.systemDefault()))
            value is Number -> value.toString()
            value is String && fieldName == "images" -> processImagesForExport(value)
            value is String && fieldName in LIST_FIELDS -> parseAndJoin(value)
            value is String -> {
                val fieldCnMap = CODE_TO_CN[entityClass]?.get(fieldName)
                if (fieldCnMap != null) escapeCsv(fieldCnMap[value] ?: value)
                else escapeCsv(value)
            }
            else -> escapeCsv(value.toString())
        }
    }

    private fun processImagesForExport(imagesJson: String): String {
        if (imagesJson.isBlank()) return ""
        val paths = try {
            json.decodeFromString<List<String>>(imagesJson)
        } catch (_: Exception) {
            try {
                listOf(imagesJson)
            } catch (_: Exception) {
                null
            }
        } ?: return escapeCsv(imagesJson) // fallback: keep original text

        val names = paths.map { path ->
            val file = File(path)
            if (file.exists()) {
                val name = "${IMAGE_PREFIX}${UUID.randomUUID()}.jpg"
                imageFileMap[name] = file
                name
            } else {
                "${IMAGE_PREFIX}${UUID.randomUUID()}.jpg"
            }
        }
        return if (names.isEmpty()) "" else escapeCsv(names.joinToString("|"))
    }

    private fun parseAndJoin(jsonStr: String): String {
        if (jsonStr.isBlank()) return ""
        return try {
            val list = json.decodeFromString<List<String>>(jsonStr)
            if (list.isEmpty()) "" else escapeCsv(list.joinToString("|"))
        } catch (_: Exception) {
            escapeCsv(jsonStr)
        }
    }

    private fun escapeCsv(value: String): String {
        return if (value.contains(',') || value.contains('"') || value.contains('\n') || value.contains('\r')) {
            "\"${value.replace("\"", "\"\"")}\""
        } else value
    }

