    /**
     * 写入物品的使用记录。
     *
     * 只有物品**本次新增**时才会走到这里——物品被跳过时，它的使用记录也必然已经存在，
     * 所以重复导入不再让使用次数无限膨胀。
     * 同一份 JSON 内部再按 (usedAt, note) 去一次重，防止包本身带了重复行。
     */
    private suspend fun importUsageRecords(raw: String?, assetId: Long) {
        if (raw.isNullOrBlank()) return
        try {
            val seen = mutableSetOf<String>()
            json.parseToJsonElement(raw).jsonArray.forEach { element ->
                val rec = element.jsonObject
                val usedAt = (rec["usedAt"] as? JsonPrimitive)?.let {
                    try { it.content.toLong() } catch (_: Exception) { null }
                } ?: System.currentTimeMillis()
                val note = (rec["note"] as? JsonPrimitive)?.contentOrNull ?: ""
                if (!seen.add(ImportKeys.usageRecord(usedAt, note))) return@forEach
                db.usageRecordDao().insertUsageRecord(UsageRecord(assetId = assetId, usedAt = usedAt, note = note))
            }
        } catch (e: Exception) {
            AppLogger.e("CsvDataExporter", "Import usage records failed", e)
        }
    }

    /**
     * 按账单重算钱包余额，守住不变量：`currentBalance == initialBalance + Σ 该钱包账单净额`。
     *
     * **为什么必须重算**：导入是「合并」，新账单会落进**已存在**的钱包；而钱包行本身
     * 因为业务键相同被跳过了，余额不会跟着动 —— 账单加了、余额没加，账实不符。
     *
     * **为什么安全**：应用自己在 `WalletEditScreen` 改初始余额时，就是把 `currentBalance`
     * 平移同一个差额。也就是说 `currentBalance` 本来就只是 `initialBalance` 的派生值，
     * 不存在「用户手填的当前余额」会被这次重算抹掉。
     *
     * @return 余额确实被修正过的钱包数（本来就对的不计）。
     */
    private suspend fun recalculateWalletBalances(walletIds: Set<Long>): Int {
        if (walletIds.isEmpty()) return 0
        val wallets = db.walletDao().getAllWallets().first().associateBy { it.id }
        val deltas = mutableMapOf<Long, Long>()
        fun add(walletId: Long?, amount: Long) {
            if (walletId != null) deltas[walletId] = (deltas[walletId] ?: 0L) + amount
        }
        for (bill in db.billDao().getAllBills().first()) {
            when (bill.type) {
                BillType.EXPENSE -> add(bill.walletId, -bill.amount)
                BillType.INCOME -> add(bill.walletId, bill.amount)
                BillType.TRANSFER -> {
                    add(bill.walletId, -bill.amount)
                    add(bill.toWalletId, bill.amount)
                }
            }
        }
        var changed = 0
        for (id in walletIds) {
            val wallet = wallets[id] ?: continue
            val expected = wallet.initialBalance + (deltas[id] ?: 0L)
            if (wallet.currentBalance != expected) {
                db.walletDao().updateBalance(id, expected)
                changed++
            }
        }
        return changed
    }

