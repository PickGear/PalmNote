    private fun parseDeletedInfo(row: Map<String, String>): Pair<Boolean, Long?> {
        val isDeleted = row["isDeleted"].toBoolean()
        return isDeleted to (if (isDeleted) parseDateOrNull(row["deletedAt"]) else null)
    }

    private fun parseDateOrNull(value: String?): Long? {
        if (value.isNullOrBlank()) return null
        return try {
            value.toLong()
        } catch (_: NumberFormatException) {
            try {
                LocalDateTime.parse(value, dateFormatter).atZone(ZoneId.systemDefault()).toInstant().toEpochMilli()
            } catch (_: Exception) {
                null
            }
        }
    }

    private fun resolveImages(csvValue: String?, pathMapping: Map<String, String>): String {
        if (csvValue.isNullOrBlank()) return ""
        val names = csvValue.split("|").map { it.trim() }.filter { it.isNotEmpty() }
        if (names.isEmpty()) return ""
        val paths = names.map { pathMapping[it] ?: it }
        return json.encodeToString(kotlinx.serialization.serializer(), paths)
    }

    private fun joinToJson(csvValue: String?): String {
        if (csvValue.isNullOrBlank()) return ""
        val items = csvValue.split("|").map { it.trim() }.filter { it.isNotEmpty() }
        return if (items.isEmpty()) "" else json.encodeToString(kotlinx.serialization.serializer(), items)
    }

