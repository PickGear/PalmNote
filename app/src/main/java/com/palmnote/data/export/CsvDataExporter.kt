    /**
     * 把 CSV 里的图片名还原成本机绝对路径。
     *
     * 映射不到的条目要分两种情况，不能一概而论：
     * - 是**我们自己生成**的名字（`img_<uuid>.jpg`）却映射不到 = 导出时文件就已经不在了，
     *   再把它当路径存回去只会留下一条永远打不开的悬空记录 → **丢弃**。
     * - **不是**我们生成的名字（手写、或别的软件给的 CSV 里可能是真实路径）→ 原样保留，
     *   不能替用户判断它有没有用。
     */
    private fun resolveImages(csvValue: String?, pathMapping: Map<String, String>): String {
        if (csvValue.isNullOrBlank()) return ""
        val names = csvValue.split("|").map { it.trim() }.filter { it.isNotEmpty() }
        if (names.isEmpty()) return ""
        val paths = names.mapNotNull { name ->
            pathMapping[name] ?: name.takeIf { !it.startsWith(IMAGE_PREFIX) }
        }
        if (paths.isEmpty()) return ""
        return json.encodeToString(kotlinx.serialization.serializer(), paths)
    }

    private fun joinToJson(csvValue: String?): String {
        if (csvValue.isNullOrBlank()) return ""
        val items = csvValue.split("|").map { it.trim() }.filter { it.isNotEmpty() }
        return if (items.isEmpty()) "" else json.encodeToString(kotlinx.serialization.serializer(), items)
    }

    private suspend fun updateCrossReferences(
        idMaps: Map<Class<*>, Map<Long, Long>>,
        importedIds: Map<Class<*>, Set<Long>>
    ) {
        val assetMap = idMaps[Asset::class.java] ?: emptyMap()
        val billMap = idMaps[Bill::class.java] ?: emptyMap()
        val walletMap = idMaps[Wallet::class.java] ?: emptyMap()
        val goalMap = idMaps[Goal::class.java] ?: emptyMap()
        val anniversaryMap = idMaps[Anniversary::class.java] ?: emptyMap()
        val momentMap = idMaps[Moment::class.java] ?: emptyMap()
        val templateMap = idMaps[RecurringTemplate::class.java] ?: emptyMap()
        val categoryMap = idMaps[CategoryConfig::class.java] ?: emptyMap()
        // 只有本次导入**新写入**的行才允许被改写引用；本地既有行哪怕 id 撞上包内旧 id 也不动
        val billIds = importedIds[Bill::class.java] ?: emptySet()
        val assetIds = importedIds[Asset::class.java] ?: emptySet()
        val momentIds = importedIds[Moment::class.java] ?: emptySet()
        val goalIds = importedIds[Goal::class.java] ?: emptySet()
        val anniversaryIds = importedIds[Anniversary::class.java] ?: emptySet()
        val categoryIds = importedIds[CategoryConfig::class.java] ?: emptySet()

        if (assetMap.isNotEmpty()) {
            db.billDao().getAllBills().first().filter { it.id in billIds }.forEach { bill ->
                var updated = false
                var newLinkedAssetId = bill.linkedAssetId
                if (newLinkedAssetId != null && newLinkedAssetId in assetMap) {
                    newLinkedAssetId = assetMap[newLinkedAssetId]
                    updated = true
                }
                if (updated) {
                    db.billDao().updateBill(bill.copy(linkedAssetId = newLinkedAssetId))
                }
            }
            db.momentDao().getAllMoments().first().filter { it.id in momentIds }.forEach { moment ->
                var updated = false
                var newLinkedAssetId = moment.linkedAssetId
                if (newLinkedAssetId != null && newLinkedAssetId in assetMap) {
                    newLinkedAssetId = assetMap[newLinkedAssetId]
                    updated = true
                }
                if (updated) {
                    db.momentDao().updateMoment(moment.copy(linkedAssetId = newLinkedAssetId))
                }
            }
            db.goalDao().getAllGoals().first().filter { it.id in goalIds }.forEach { goal ->
                var updated = false
                var newLinkedAssetId = goal.linkedAssetId
                if (newLinkedAssetId != null && newLinkedAssetId in assetMap) {
                    newLinkedAssetId = assetMap[newLinkedAssetId]
                    updated = true
                }
                if (updated) {
                    db.goalDao().updateGoal(goal.copy(linkedAssetId = newLinkedAssetId))
                }
            }
        }

        if (billMap.isNotEmpty()) {
            db.assetDao().getAllAssets().first().filter { it.id in assetIds }.forEach { asset ->
                var updated = false
                var newLinkedBillId = asset.linkedBillId
                if (newLinkedBillId != null && newLinkedBillId in billMap) {
                    newLinkedBillId = billMap[newLinkedBillId]
                    updated = true
                }
                if (updated) {
                    db.assetDao().updateAsset(asset.copy(linkedBillId = newLinkedBillId))
                }
            }
        }

        if (walletMap.isNotEmpty()) {
            db.billDao().getAllBills().first().filter { it.id in billIds }.forEach { bill ->
                var updated = false
                var newWalletId = bill.walletId
                var newToWalletId = bill.toWalletId
                if (newWalletId != null && newWalletId in walletMap) {
                    newWalletId = walletMap[newWalletId]
                    updated = true
                }
                if (newToWalletId != null && newToWalletId in walletMap) {
                    newToWalletId = walletMap[newToWalletId]
                    updated = true
                }
                if (updated) {
                    db.billDao().updateBill(bill.copy(walletId = newWalletId, toWalletId = newToWalletId))
                }
            }
        }

        if (goalMap.isNotEmpty()) {
            for ((oldId, newId) in goalMap) {
                // 仅当目标本身是本次新写入的才迁移其打卡记录；本地既有目标的打卡不许动
                if (newId !in goalIds) continue
                db.goalCheckInDao().getCheckInsByGoal(oldId).first().forEach { checkIn ->
                    db.goalCheckInDao().updateCheckIn(checkIn.copy(goalId = newId))
                }
            }
            db.momentDao().getAllMoments().first().filter { it.id in momentIds }.forEach { moment ->
                var updated = false
                var newLinkedGoalId = moment.linkedGoalId
                if (newLinkedGoalId != null && newLinkedGoalId in goalMap) {
                    newLinkedGoalId = goalMap[newLinkedGoalId]
                    updated = true
                }
                if (updated) {
                    db.momentDao().updateMoment(moment.copy(linkedGoalId = newLinkedGoalId))
                }
            }
        }

        if (anniversaryMap.isNotEmpty()) {
            db.momentDao().getAllMoments().first().filter { it.id in momentIds }.forEach { moment ->
                var updated = false
                var newLinkedAnniversaryId = moment.linkedAnniversaryId
                if (newLinkedAnniversaryId != null && newLinkedAnniversaryId in anniversaryMap) {
                    newLinkedAnniversaryId = anniversaryMap[newLinkedAnniversaryId]
                    updated = true
                }
                if (updated) {
                    db.momentDao().updateMoment(moment.copy(linkedAnniversaryId = newLinkedAnniversaryId))
                }
            }
        }

        if (momentMap.isNotEmpty()) {
            db.assetDao().getAllAssets().first().filter { it.id in assetIds }.forEach { asset ->
                var updated = false
                var newLinkedMomentId = asset.linkedMomentId
                if (newLinkedMomentId != null && newLinkedMomentId in momentMap) {
                    newLinkedMomentId = momentMap[newLinkedMomentId]
                    updated = true
                }
                if (updated) {
                    db.assetDao().updateAsset(asset.copy(linkedMomentId = newLinkedMomentId))
                }
            }
            db.anniversaryDao().getAllAnniversaries().first().filter { it.id in anniversaryIds }.forEach { anniversary ->
                var updated = false
                var newLinkedMomentId = anniversary.linkedMomentId
                if (newLinkedMomentId != null && newLinkedMomentId in momentMap) {
                    newLinkedMomentId = momentMap[newLinkedMomentId]
                    updated = true
                }
                if (updated) {
                    db.anniversaryDao().updateAnniversary(anniversary.copy(linkedMomentId = newLinkedMomentId))
                }
            }
        }

        // 账单 → 周期模板。漏掉这条会让「合并后账单挂到别人家的模板上」，
        // 比断开关联更糟：模板会自动按它生成新账单。
        if (templateMap.isNotEmpty()) {
            db.billDao().getAllBills().first().filter { it.id in billIds }.forEach { bill ->
                val recurringId = bill.recurringId
                if (recurringId != null && recurringId in templateMap) {
                    db.billDao().updateBill(bill.copy(recurringId = templateMap[recurringId]))
                }
            }
        }

        // 分类 → 父分类。子分类挂在错误的父节点下，用户在分类管理里会看到一棵错树。
        if (categoryMap.isNotEmpty()) {
            db.categoryConfigDao().getAllCategories().first().filter { it.id in categoryIds }.forEach { category ->
                val parentId = category.parentId
                if (parentId != null && parentId in categoryMap) {
                    db.categoryConfigDao().update(category.copy(parentId = categoryMap[parentId]))
                }
            }
        }
    }

    private fun String?.toBoolean(): Boolean = this == "是" || this == "true"
