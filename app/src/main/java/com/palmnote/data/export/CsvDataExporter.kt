                createdAt = parseDateOrNull(row["createdAt"]) ?: System.currentTimeMillis(),
                updatedAt = parseDateOrNull(row["updatedAt"]) ?: System.currentTimeMillis()
            )
        } catch (_: Exception) { null }
    }

