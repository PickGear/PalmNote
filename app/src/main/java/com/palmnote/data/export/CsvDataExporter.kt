    /**
     * 事务内的导入主循环。
     *
     * 旧实现在这里做的是：把 CSV 里的 `id` 原样写库，`id` 撞了就靠
     * `OnConflictStrategy.REPLACE` **覆盖**。于是「导入一份几周前的自己包」
     * 会把这几周的记录回滚成包里的旧值，全程一句提示都没有。
     *
     * 现在三条规则：
     *
     * 1. **业务键判重**：键已存在 → 跳过，绝不覆盖（键怎么取见 [ImportKeys]）。
     * 2. **id 碰撞改派**：键不存在、但包里带的 `id` 已被本机另一条记录占用
     *    （跨设备合并时的典型情况）→ 不硬写该 id，交给 Room 自增，并登记
     *    `旧 id → 新 id` 供收尾时重写交叉引用。
     * 3. **只为真的写了东西的钱包重算余额**：守住 `余额 == 初始余额 + Σ账单净额`。
     */
    private suspend fun importIntoDb(
        zipEntries: Map<String, ByteArray>,
        pathMapping: Map<String, String>
    ): ImportReport {
        val idMaps = mutableMapOf<Class<*>, MutableMap<Long, Long>>()
        // 业务键 → 记录 id（含本次刚写入的，因此同一文件内的重复行也会被拦下）
        val knownKeys = mutableMapOf<Class<*>, MutableMap<String, Long>>()
        // 每张表已被占用的主键，用来判断「原样写这个 id 会不会压到别人」
        val occupiedIds = mutableMapOf<Class<*>, MutableSet<Long>>()
        // 本次导入**新写入**的行 id（按实体类）：交叉引用改写只允许作用于这些行
        val importedIds = mutableMapOf<Class<*>, MutableSet<Long>>()
        // 本次写入的钱包（最终 id）／被本次新账单引用的钱包（可能是包里的旧 id）
        val insertedWalletIds = mutableSetOf<Long>()
        val referencedWalletIds = mutableSetOf<Long>()

        for ((clazz, entities) in existingEntitySnapshot()) {
            val ids = occupiedIds.getOrPut(clazz) { mutableSetOf() }
            val keys = knownKeys.getOrPut(clazz) { mutableMapOf() }
            for (entity in entities) {
                val id = entityIdOf(clazz, entity) ?: continue
                ids.add(id)
                businessKeyOf(clazz, entity)?.let { keys.putIfAbsent(it, id) }
            }
        }

        var inserted = 0
        var skipped = 0

        for ((filename, bytes) in zipEntries) {
            if (filename.startsWith("images/") || !filename.endsWith(".csv")) continue
            val rows = csvToRows(String(bytes, Charsets.UTF_8))
            if (rows.isEmpty()) continue

            for (row in rows) {
                val clazz = CLASS_BY_TYPE_NAME[row["实体类型"]] ?: continue
                val translated = translateRow(row, clazz)
                val parsed = parseHandler[clazz]?.invoke(translated, pathMapping) ?: continue

                // 先把「此刻已经能确定」的交叉引用落到本机 id 上再算键，
                // 否则跨设备合并时同一次打卡会因为目标 id 不同而被当成两条。
                // （导出侧父行一定排在子行之前，所以映射此时已就绪。）
                val resolved = resolveIncomingRefs(clazz, parsed, idMaps)
                val key = businessKeyOf(clazz, resolved)

                if (key != null) {
                    val existingId = knownKeys.getOrPut(clazz) { mutableMapOf() }[key]
                    if (existingId != null) {
                        // 同一条已经在库里：跳过。跳过 = 保留现有数据，不是失败。
                        entityIdOf(clazz, resolved)?.let { recordIdMap(idMaps, clazz, it, existingId) }
                        skipped++
                        continue
                    }
                }

                val rawId = entityIdOf(clazz, resolved) ?: 0L
                val occupied = occupiedIds.getOrPut(clazz) { mutableSetOf() }
                val toInsert = if (rawId != 0L && rawId in occupied) withZeroId(clazz, resolved) else resolved

                val newId = insertHandler[clazz]?.invoke(toInsert) ?: continue
                recordIdMap(idMaps, clazz, rawId, newId)
                occupied.add(newId)
                importedIds.getOrPut(clazz) { mutableSetOf() }.add(newId)
                if (key != null) {
                    val keys = knownKeys.getOrPut(clazz) { mutableMapOf() }
                    if (!keys.containsKey(key)) keys[key] = newId
                }
                inserted++

                if (clazz == Wallet::class.java) {
                    insertedWalletIds.add(newId)
                } else if (clazz == Bill::class.java) {
                    val bill = toInsert as? Bill
                    bill?.walletId?.let { referencedWalletIds.add(it) }
                    bill?.toWalletId?.let { referencedWalletIds.add(it) }
                } else if (clazz == Asset::class.java) {
                    importUsageRecords(row["usageRecords"], newId)
                }
            }
        }

        if (idMaps.isNotEmpty()) {
            // 交叉引用改写只允许作用于**本次导入写入的行**：
            // 无差别改写全表会让本地既有行里恰好撞上包内旧 id 的引用被错改
            updateCrossReferences(idMaps, importedIds)
        }

        // 只有本次真的动了账单或钱包，余额才可能与账单脱节
        val walletMap = idMaps[Wallet::class.java].orEmpty()
        val walletsToRecalculate = mutableSetOf<Long>()
        walletsToRecalculate.addAll(insertedWalletIds)
        referencedWalletIds.forEach { walletsToRecalculate.add(walletMap[it] ?: it) }

        return ImportReport(
            inserted = inserted,
            skipped = skipped,
            walletsRecalculated = recalculateWalletBalances(walletsToRecalculate)
        )
    }

