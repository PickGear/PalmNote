    suspend fun exportToUri(uri: Uri, scope: ExportScope = ExportScope.ALL): Result<String> {
        return withContext(Dispatchers.IO) {
            try {
                imageFileMap.clear()
                val wallets = db.walletDao().getAllWallets().first()
                val bills = db.billDao().getAllBills().first()
                val templates = db.recurringTemplateDao().getAllTemplates().first()
                val budgets = db.budgetDao().getAllBudgets().first()
                val assets = db.assetDao().getAllAssets().first()
                val usageRecords = db.usageRecordDao().getAllUsageRecords().first()
                val goals = db.goalDao().getAllGoals().first()
                val goalCheckIns = if (goals.isNotEmpty()) {
                    db.goalCheckInDao().getCheckInsByGoalIds(goals.map { it.id }).first()
                } else {
                    emptyList()
                }
                val anniversaries = db.anniversaryDao().getAllAnniversaries().first()
                val moments = db.momentDao().getAllMoments().first()
                val categoryConfigs = db.categoryConfigDao().getAllCategories().first()
                val customTags = db.customTagDao().getAllTags().first()
                val categoryMappings = db.categoryMappingDao().getAllMappings().first()

                val entityMap: Map<Class<*>, List<*>> = mapOf(
                    Bill::class.java to bills, Wallet::class.java to wallets,
                    RecurringTemplate::class.java to templates, Budget::class.java to budgets,
                    CategoryConfig::class.java to categoryConfigs, CategoryMapping::class.java to categoryMappings,
                    Asset::class.java to assets,
                    Goal::class.java to goals, GoalCheckIn::class.java to goalCheckIns,
                    Anniversary::class.java to anniversaries, Moment::class.java to moments,
                    CustomTag::class.java to customTags
                )

                var totalCount = 0
                var imageCount = 0
                val usageByAssetId = usageRecords.groupBy { it.assetId }
                val usageJsonByAssetId = usageByAssetId.mapValues { (_, records) ->
                    records.joinToString(",", "[", "]") { r ->
                        val m = buildMap<String, kotlinx.serialization.json.JsonElement> {
                            put("usedAt", JsonPrimitive(r.usedAt))
                            put("note", JsonPrimitive(r.note))
                        }
                        JsonObject(m).toString()
                    }
                }

                val extraColumns: Map<Class<*>, List<Pair<String, (Any?) -> Any>>> = mapOf(
                    Asset::class.java to listOf("usageRecords" to { entity: Any? ->
                        val asset = entity as Asset
                        usageJsonByAssetId[asset.id] ?: ""
                    })
                )

                // 部分导出会让「物品」脱离账单与瞬间独立出走。那两个字段存的是本机自增 id，
                // 在别的库里毫无意义；而导入侧是「保留原 id + OnConflictStrategy.REPLACE」，
                // 悬空 id 可能撞上同 id 记录、从「没有关联」变成「错误关联」（物品挂到别人的账单上）。
                // 所以非完整导出时干脆不带这两列 —— 宁可丢关联，不能错关联。
                val crossGroupExcluded: Map<Class<*>, Set<String>> =
                    if (scope.isComplete) emptyMap()
                    else mapOf(Asset::class.java to setOf("linkedBillId", "linkedMomentId"))

                val themeMode = preferencesManager.themeMode.first()
                val defaultBillType = preferencesManager.defaultBillType.first()
                val budgetReminderEnabled = preferencesManager.budgetReminderEnabled.first()
                val prefsJson = JsonObject(buildMap {
                    put("themeMode", JsonPrimitive(themeMode))
                    put("defaultBillType", JsonPrimitive(defaultBillType))
                    put("budgetReminderEnabled", JsonPrimitive(budgetReminderEnabled))
                }).toString()

                val outputStream = context.contentResolver.openOutputStream(uri)
                    ?: return@withContext Result.failure(Exception(context.getString(R.string.export_error_create_file)))
                outputStream.use { os ->
                    ZipOutputStream(BufferedOutputStream(os)).use { zos ->
                        for ((groupScope, csvName, classes) in CSV_GROUPS) {
                            if (scope != ExportScope.ALL && groupScope != scope) continue
                            val active = classes.mapNotNull { clazz ->
                                val typeName = TYPE_NAME_BY_CLASS[clazz] ?: return@mapNotNull null
                                val entities = entityMap[clazz] ?: return@mapNotNull null
                                (typeName to entities).takeIf { it.second.isNotEmpty() }
                            }
                            if (active.isEmpty()) continue
                            totalCount += active.sumOf { (_, list) -> list.size }
                            val csv = buildGroupCsv(active, extraColumns, crossGroupExcluded)
                            val data = csv.toByteArray(Charsets.UTF_8)
                            val entry = ZipEntry("$csvName.csv")
                            entry.size = data.size.toLong()
                            zos.putNextEntry(entry)
                            zos.write(data)
                            zos.closeEntry()
                        }

                        // 设置类条目只在完整导出时随包出去：部分导出是「给别人读的内容清单」，
                        // 顺带把本机主题、默认账单类型带过去没有道理，导入方会被莫名改设置。
                        if (scope.isComplete) {
                            val prefsData = prefsJson.toByteArray(Charsets.UTF_8)
                            val prefsEntry = ZipEntry(PREFERENCES_ENTRY)
                            prefsEntry.size = prefsData.size.toLong()
                            zos.putNextEntry(prefsEntry)
                            zos.write(prefsData)
                            zos.closeEntry()
                        }

                        for ((name, file) in imageFileMap) {
                            if (!file.exists()) continue
                            val imageBytes = file.readBytes()
                            val imageEntry = ZipEntry("images/$name")
                            imageEntry.size = imageBytes.size.toLong()
                            zos.putNextEntry(imageEntry)
                            zos.write(imageBytes)
                            zos.closeEntry()
                            imageCount++
                        }

                        zos.flush()
                    }
                }
                val msg = if (imageCount > 0) context.getString(R.string.export_success_images, totalCount, imageCount)
                          else context.getString(R.string.export_success, totalCount)
                Result.success(msg)
            } catch (e: AppException) {
                Result.failure(e)
            } catch (e: java.io.IOException) {
                Result.failure(AppException.Io(context.getString(R.string.export_error_io, e.message), e))
            } catch (e: kotlinx.serialization.SerializationException) {
                Result.failure(AppException.Serialization(context.getString(R.string.export_error_serialization, e.message), e))
            } catch (e: Exception) {
                Result.failure(AppException.Unknown(context.getString(R.string.export_error_unknown, e.message), e))
            }
        }
    }

    suspend fun importFromUri(uri: Uri): Result<ImportReport> {
        return withContext(Dispatchers.IO) {
            val tempFile = File(context.cacheDir, "csvimport_${UUID.randomUUID()}.tmp")
            try {
                context.contentResolver.openInputStream(uri)?.use { input ->
                    tempFile.outputStream().use { output -> input.copyTo(output) }
                } ?: return@withContext Result.failure(Exception(context.getString(R.string.export_error_read_file)))

                val zipEntries = mutableMapOf<String, ByteArray>()
                var totalBytes = 0L
                FileInputStream(tempFile).use { fis ->
                    ZipInputStream(BufferedInputStream(fis)).use { zis ->
                        var entry = zis.nextEntry
                        while (entry != null) {
                            if (!entry.isDirectory) {
                                val bytes = zis.readBytes()
                                totalBytes += bytes.size
                                // 全部条目驻留内存（含图片）：给一个明确的过大提示，而不是等 OOM 崩溃
                                if (totalBytes > MAX_IMPORT_BYTES) {
                                    return@withContext Result.failure(
                                        AppException.Unknown(context.getString(R.string.import_error_too_large))
                                    )
                                }
                                zipEntries[entry.name] = bytes
                            }
                            zis.closeEntry()
                            entry = zis.nextEntry
                        }
                    }
                }

                val imagesDir = File(context.filesDir, "images")
                if (!imagesDir.exists()) imagesDir.mkdirs()
                val pathMapping = mutableMapOf<String, String>()

                for ((name, bytes) in zipEntries) {
                    if (name.startsWith("images/") && name.length > 7) {
                        val filename = name.substringAfter("images/")
                        // 防 zip-slip：拒绝含路径分隔符/相对路径的条目名
                        if (filename.contains("..") || filename.contains("/") || filename.contains("\\")) continue
                        val destFile = File(imagesDir, filename)
                        // 图片名是导出侧的原始文件名（含 uuid）：同机重复导入时直接复用，
                        // 否则每次导入都会把整套图片再落一遍盘、留下成堆无引用的孤儿文件
                        if (!destFile.exists()) destFile.writeBytes(bytes)
                        pathMapping[filename] = destFile.absolutePath
                    }
                }

                // 全部 DB 写入包在一个事务里：要么全成，要么全撤，不留半截导入。
                // 用 withTransaction（suspend 事务）包裹 suspend DAO 调用；
                // 旧写法 runInTransaction { runBlocking { ... } } 会与 Room 事务执行器争用单线程而可能死锁。
                val report = db.withTransaction { importIntoDb(zipEntries, pathMapping) }

                if (report.inserted > 0) zipEntries[PREFERENCES_ENTRY]?.let { bytes ->
                    try {
                        val prefsObj = json.parseToJsonElement(String(bytes, Charsets.UTF_8)).jsonObject
                        prefsObj["themeMode"]?.let { v ->
                            val value = (v as? JsonPrimitive)?.contentOrNull ?: v.toString()
                            preferencesManager.setThemeMode(value)
                        }
                        prefsObj["defaultBillType"]?.let { v ->
                            val value = (v as? JsonPrimitive)?.contentOrNull ?: v.toString()
                            preferencesManager.setDefaultBillType(value)
                        }
                        prefsObj["budgetReminderEnabled"]?.let { v ->
                            val str = (v as? JsonPrimitive)?.contentOrNull ?: v.toString()
                            val enabled = str == "true" || str == "是"
                            preferencesManager.setBudgetReminderEnabled(enabled)
                        }
                    } catch (e: Exception) { AppLogger.e("CsvDataExporter", "Import preferences failed", e) }
                }

                Result.success(report)
            } catch (e: AppException) {
                Result.failure(e)
            } catch (e: java.io.IOException) {
                Result.failure(AppException.Io(context.getString(R.string.import_error_io, e.message), e))
            } catch (e: kotlinx.serialization.SerializationException) {
                Result.failure(AppException.Serialization(context.getString(R.string.import_error_parse, e.message), e))
            } catch (e: Throwable) {
                // OutOfMemoryError 是 Error 不是 Exception：大包导入给失败提示而非闪退
                Result.failure(AppException.Unknown(context.getString(R.string.import_error_unknown, e.message), e))
            } finally {
                tempFile.delete()
            }
        }
    }

